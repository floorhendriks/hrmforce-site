export function documentenPerProduct(lang = "nl") {
  const uit = {};
  for (const [sleutel, ids] of Object.entries(PER_PRODUCT)) {
    const rij = ids.map((id) => DOCS[id]).filter(Boolean).map((d) => ({
      href: d.href,
      titel: d.titel[lang] || d.titel.en || d.titel.nl,
      meta: `${d.bron} \u00b7 ${d.taal}` + (d.mb ? ` \u00b7 ${d.mb} MB` : ""),
    }));
    if (rij.length) uit[sleutel] = rij;
  }
  return uit;
}

