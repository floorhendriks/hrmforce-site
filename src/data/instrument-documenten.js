for (const bron of [THEMAPAGINAS, TESTHUBS]) {
  for (const [sleutel, pagina] of Object.entries(bron)) {
    for (const [taal, slug] of Object.entries(pagina.slug || {})) {
      const pad = taal === "nl" ? `/${slug}/` : `/${taal}/${slug}/`;
      PAD_NAAR_SLEUTEL[pad] = sleutel;
    }
  }
}

export function documentenVoor(pathname) {
  const pad = pathname.endsWith("/") ? pathname : pathname + "/";
  const sleutel = PAD_NAAR_SLEUTEL[pad];
  return (sleutel && PER_PAGINA[sleutel]) || [];
}

